// Classification Helpers
export const classifyEventType = (agenda: string): EventType => {
  const text = (agenda || '').toLowerCase();
  if (text.includes('republic day') || text.includes('good friday') || text.includes('may day') || text.includes('holiday') || text.includes('leave')) {
    return 'Holiday';
  }
  if (text.includes('knowledge sharing')) return 'Knowledge Sharing Series';
  if (text.includes('informatica')) return 'Informatica Training';
  if (text.includes('antigravity')) return 'Antigravity Training';
  if (text.includes('databricks training') || text.includes('databricks deep dive')) return 'Databricks Training';
  if (text.includes('ba training') || text.includes('business analyst') || text.includes('requirements engineering')) return 'BA Training';
  if (text.includes('de training') || text.includes('data engineering')) return 'DE Training';
  if (text.includes('tools training') || text.includes('tool masterclass') || text.includes('dbt masterclass')) return 'Tools Training';
  if (text.includes('technical training') || text.includes('tech deep dive')) return 'Technical Training';
  if (text.includes('soft skills') || text.includes('communication') || text.includes('leadership')) return 'Soft Skills Training';
  if (text.includes('management training') || text.includes('agile capacity') || text.includes('scrum')) return 'Management Training';
  if (text.includes('external training') || text.includes('vendor training')) return 'External Training';
  if (text.includes('upskilling') || text.includes('skill upskilling')) return 'Upskilling Session';
  if (text.includes('cert prep') || text.includes('certification preparation') || text.includes('exam review')) return 'Certification Preparation';
  if (text.includes('internal training')) return 'Internal Training';
  if (text.includes('module test')) return 'Assessment';
  if (text.includes('mock test')) return 'Mock Test';
  if (text.includes('workshop')) return 'Workshop';
  if (text.includes('practice')) return 'Practice';
  if (text.includes('hr meet') || text.includes('orientation') || text.includes('welcome')) return 'HR Event';
  if (text.includes('one-to-one') || text.includes('feedback')) return 'Feedback';
  if (text.includes('simulation project')) return 'Project';
  if (text.includes('di certification evaluation')) return 'Evaluation';
  if (text.includes('di certification')) return 'Certification';
  if (text.includes('sign off')) return 'Sign Off';
  if (text.includes('bootcamp')) return 'Bootcamp Training';
  return 'Training';
};

export const classifyLearningTrack = (moduleName: string): LearningTrack => {
  const m = (moduleName || '').toLowerCase();
  if (m.includes('sql') || m.includes('t-sql') || m.includes('python') || m.includes('orientation') || m.includes('hr')) {
    return 'Common Foundation';
  }
  if (m.includes('dbt') || m.includes('snowflake')) {
    return 'DBT & Snowflake';
  }
  if (m.includes('databricks') || m.includes('pyspark')) {
    return 'Databricks';
  }
  return 'Shared';
};

